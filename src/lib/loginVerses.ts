const DAY_MS = 86_400_000;
const COLOMBIA_OFFSET_MS = -5 * 60 * 60 * 1000;

// Each shuffled cycle is shared by all visitors and stable across refreshes.
function shuffledCycle(cycle: number): number[] {
  let seed = (cycle ^ 0x9e3779b9) >>> 0;
  const order = LOGIN_VERSES.map((_, index) => index);
  for (let index = order.length - 1; index > 0; index--) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    const other = seed % (index + 1);
    [order[index], order[other]] = [order[other], order[index]];
  }
  return order;
}

export function getDailyLoginVerse(now: Date = new Date()): LoginVerse {
  const day = Math.floor((now.getTime() + COLOMBIA_OFFSET_MS) / DAY_MS);
  const cycle = Math.floor(day / LOGIN_VERSES.length);
  const position = ((day % LOGIN_VERSES.length) + LOGIN_VERSES.length) % LOGIN_VERSES.length;
  const order = shuffledCycle(cycle);
  // Only swap the first two: the last entry stays stable, including across cycles.
  if (order[0] === shuffledCycle(cycle - 1).at(-1)) {
    [order[0], order[1]] = [order[1], order[0]];
  }
  return LOGIN_VERSES[order[position]];
}

export function millisecondsToNextVerse(now: Date = new Date()): number {
  const localTime = now.getTime() + COLOMBIA_OFFSET_MS;
  return DAY_MS - ((localTime % DAY_MS) + DAY_MS) % DAY_MS;
}
